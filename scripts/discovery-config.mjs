// ─── Catalog enrichment ─────────────────────────────────────────────────────

// Returns an array of plain recipe items merged with their meta sidecar:
// { id, name, origin, category, tipType, pairingsType, nutrition, servings,
//   time, costRon, tags, desc }.
// Missing meta is tolerated (item gets empty tags + undefined time/cost) so
// older recipes don't break selectors. Stable order: ascending id.
export function enrichCatalog({ recipes, recipesMeta }) {
  if (!Array.isArray(recipes)) throw new TypeError('enrichCatalog: recipes must be an array');
  if (!recipesMeta || typeof recipesMeta !== 'object') {
    throw new TypeError('enrichCatalog: recipesMeta must be an object');
  }
  const out = [];
  for (const r of recipes) {
    if (!r || typeof r.id !== 'number') continue;
    const meta = recipesMeta[r.id] || {};
    out.push({
      id: r.id,
      name: r.name || {},
      origin: r.origin || {},
      category: r.category || {},
      tipType: r.tipType || '',
      pairingsType: r.pairingsType || '',
      nutrition: r.nutrition || {},
      servings: typeof r.servings === 'number' ? r.servings : null,
      time: typeof meta.time === 'number' ? meta.time : null,
      costRon: typeof meta.costRon === 'number' ? meta.costRon : null,
      tags: Array.isArray(meta.tags) ? meta.tags.slice() : [],
      desc: meta.desc || {},
    });
  }
  out.sort((a, b) => a.id - b.id);
  return out;
}

// ─── Primitive predicates ───────────────────────────────────────────────────

function originKeyEn(item) {
  const v = item.origin?.en;
  return typeof v === 'string' ? v.trim().toLowerCase() : '';
}

// Multiplicative mixer for deterministic-but-varied tie-breaking. Same
// technique as the same-cuisine `relWeight` mixer in generate-content.mjs
// (line ~4022) — kept here as a near-duplicate rather than shared/imported
// so this module stays a pure, dependency-free leaf. Math.imul keeps the
// 32-bit multiplication exact; shifting by 7 mixes high/low bits so the
// hash doesn't degenerate into ~sort-by-id.
function bridgeWeight(currentId, candidateId) {
  return Math.imul((candidateId + 1) ^ ((currentId + 1) << 7) ^ ((currentId + 1) >>> 3), 2654435761) >>> 0;
}

// Cross-cuisine bridge: items from a different origin that are actually
// similar to `currentItem` — same kind of dish first (soup↔soup,
// seafood↔seafood, dessert↔dessert...), then diet/practicality tag overlap
// as a secondary signal, then a deterministic per-(current,candidate) hash
// to break remaining ties — NOT ascending id.
//
// Ranking on tags alone was too weak a similarity signal on its own: tags
// are just 9 broad diet/practicality labels (quick, family, vegetarian...),
// so e.g. Miso Soup (a soup) matched Menemen (scrambled eggs) and Tzatziki
// (a yoghurt dip) purely because all three happen to be "quick" and
// "vegetarian" — nothing about them is actually alike. Layering in
// dishKindOf() (derived from tipType/pairingsType) means a soup is ranked
// against other soups before an unrelated dish that merely shares a tag.
//
// Separately, an earlier id-ascending tiebreak meant any recipe sharing
// just one generic tag always lost the tie to the same handful of
// lowest-id recipes: audited pre-fix, Cheeseburger (id 7) and Spaghetti
// Carbonara (id 1) each showed up as a "similar dish" on 167 of 274
// recipes (61% of the whole site), Tacos on 153 — regardless of relevance.
// The hash spreads which candidate wins a tie across many different
// current recipes while staying stable across rebuilds.
export function selectByTagMix(catalog, currentItem, { exclude = [], max = 4 } = {}) {
  if (!currentItem || !Array.isArray(currentItem.tags) || currentItem.tags.length === 0) return [];
  const wantTags = new Set(currentItem.tags);
  const currentOrigin = originKeyEn(currentItem);
  const currentId = currentItem.id || 0;
  const currentKind = dishKindOf(currentItem);
  const skip = new Set([currentItem.id, ...exclude]);
  const scored = [];
  for (const it of catalog) {
    if (skip.has(it.id)) continue;
    if (originKeyEn(it) === currentOrigin) continue;
    let overlap = 0;
    for (const t of it.tags) if (wantTags.has(t)) overlap++;
    const kindMatch = currentKind !== null && dishKindOf(it) === currentKind;
    if (overlap > 0 || kindMatch) {
      scored.push({ it, overlap, kindMatch, w: bridgeWeight(currentId, it.id || 0) });
    }
  }
  scored.sort((a, b) =>
    (b.kindMatch - a.kindMatch) || (b.overlap - a.overlap) || (a.w - b.w));
  return scored.slice(0, max).map(s => s.it);
}

// ─── Locale-aware link helper ───────────────────────────────────────────────

// Decides whether a discovery card for `recipe` in locale `lang` should link
// to the per-recipe detail page or degrade to the cuisine hub. Returns:
//   { target: 'recipe' | 'hub', lang, originEn }
// Callers compose the final URL using their own slug + lang prefix maps
// (kept in scripts/generate-content.mjs). Keeping URL construction out of
// this module avoids duplicating the RECIPE_LANG / cuisineSlug logic.
export function resolveDiscoveryTarget(recipe, lang) {
  const originEn = recipe?.origin?.en || '';
  if (RECIPE_DETAIL_LANGS.has(lang)) {
    return { target: 'recipe', lang, originEn };
  }
  return { target: 'hub', lang, originEn };
}
