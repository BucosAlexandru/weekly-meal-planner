// Discovery helpers for the generated recipe pages — related-cuisine bridges and
// deterministic related-recipe selection.
//
// Pure leaf module. No I/O, no side effects, no imports from generate-content.mjs.
// `enrichCatalog({ recipes, recipesMeta })` is called once, and its result is passed
// to `selectByTagMix`, which returns a new array sorted by recipe id ascending
// so identical inputs always produce identical output (stable across builds).
// recipes-budget.js is intentionally NOT consumed here — Phase 7 keeps the budget
// set planner-only.

// ─── Constants ──────────────────────────────────────────────────────────────

// Locales where a per-recipe detail page is actually generated by
// scripts/generate-content.mjs (RECIPE_LANG table). Recipe details are
// emitted for all 14 locales today (175 recipes × 14 langs = 2,450 pages),
// so resolveDiscoveryTarget returns 'recipe' for every locale. A separate
// config concept (e.g. "which locales should render new discovery strips")
// belongs at the call site, not in this set.
export const RECIPE_DETAIL_LANGS = new Set(['ro','en','es','fr','de','pt','ru','ar','zh','ja','hi','tr','it','ko']);

// Dish-kind buckets derived from `tipType` / `pairingsType` in recipes.js.
// Each bucket lists the raw values that should count as a match.
export const DISH_KIND = {
  soup:    new Set(['soup']),
  pasta:   new Set(['pasta']),
  meat:    new Set(['meat']),
  veg:     new Set(['veg']),
  seafood: new Set(['seafood', 'fish']),
  asian:   new Set(['japanese', 'asian']),
  dessert: new Set(['dessert']),
  salad:   new Set(['salad']),
};

// Reverse lookup (raw tipType/pairingsType value → bucket key), built once
// from DISH_KIND so the two never drift apart. `tipType` is meant to be a
// dish-kind field, but several past batches wrote the cuisine name into it
// instead (e.g. 'korean', 'italian', 'french', 'romanian') or left a stray
// 'def' placeholder — those simply aren't in DISH_KIND, so they resolve to
// `null` below and get no dish-kind bonus, same as before this change
// (pure tag-overlap ranking). Fixing that mislabeled data is a separate,
// recipe-by-recipe content task, not something this lookup should guess at.
const DISH_KIND_BY_RAW = new Map();
for (const [kind, raws] of Object.entries(DISH_KIND)) {
  for (const raw of raws) DISH_KIND_BY_RAW.set(raw, kind);
}

function dishKindOf(item) {
  return DISH_KIND_BY_RAW.get(item.tipType) || DISH_KIND_BY_RAW.get(item.pairingsType) || null;
}

